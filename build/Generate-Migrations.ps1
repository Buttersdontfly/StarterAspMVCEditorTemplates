#!/usr/bin/env pwsh
<#
.SYNOPSIS
    Generates the EF migrations that ship inside the template.

.DESCRIPTION
    Migrations cannot be written by hand: EF derives them from the model, and the
    snapshot must match exactly or the next `migrations add` misbehaves. So this
    generates a throwaway project from the template, runs `dotnet ef migrations
    add` against it, and copies the result back into the template content.

    Run after ANY change to AppDbContext or the Identity configuration, then
    commit the result.

    Requires: .NET SDK, and dotnet-ef (installed automatically if missing).
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$repo = Split-Path $PSScriptRoot -Parent
Push-Location $repo

try {
    $content = 'src/StarterAspMVCEditorTemplates.Templates/content/StarterAspMVCEditorTemplates'
    $work = Join-Path ([System.IO.Path]::GetTempPath()) "mig-$(Get-Random)"

    # dotnet-ef is a LOCAL tool, pinned in .config/dotnet-tools.json.
    #
    # A global tool was the obvious choice and the wrong one. Installing it
    # globally puts it in ~/.dotnet/tools, which is not on PATH until the shell
    # restarts, so the very first run after a clean machine or a wiped tools
    # folder failed with "dotnet-ef does not exist" immediately after installing
    # it. A local tool needs no PATH entry, and pinning the version means the
    # migrations are generated by the same EF as the project references.
    dotnet tool restore
    if ($LASTEXITCODE -ne 0) {
        throw 'Could not restore local tools. Check .config/dotnet-tools.json and that you are online.'
    }

    # No | Out-Null here: it would swallow dotnet's output, including errors.
    & (Join-Path $PSScriptRoot 'Install-TemplateLocally.ps1')

    # Migrations are provider specific, so each provider gets its own set,
    # generated from a project created with that provider selected. Generating
    # does NOT need a live server -- `dotnet ef migrations add` only needs the
    # provider assembly -- so SQL Server migrations can be produced on any
    # machine, including a Linux CI runner.
    foreach ($provider in @(
        @{ Option = 'sqlite';    Folder = 'Sqlite' },
        @{ Option = 'sqlserver'; Folder = 'SqlServer' }
    )) {
        $projectDir = Join-Path $work $provider.Option
        Write-Host "Generating $($provider.Folder) migrations..." -ForegroundColor Cyan

        # --no-restore, then restore explicitly: the post-creation restore inside
        # `dotnet new` reports failure through a generic "Post action failed"
        # message that hides the real NuGet error.
        dotnet new starterasp-mvc -n MigrationHost -o $projectDir `
            --auth identity --database $provider.Option --no-restore
        if ($LASTEXITCODE -ne 0) { throw "Template instantiation failed for $($provider.Option)." }

        $csproj = Join-Path $projectDir 'src/MigrationHost/MigrationHost.csproj'

        dotnet restore $csproj
        if ($LASTEXITCODE -ne 0) { throw "Restore failed for $($provider.Option)." }

        # Build explicitly before dotnet ef: `dotnet ef` builds internally and
        # reports only "Build failed", swallowing the compiler output.
        dotnet build $csproj
        if ($LASTEXITCODE -ne 0) {
            throw @"
The generated project does not compile for $($provider.Option). The errors above are the real ones.
The project is still on disk: $projectDir
"@
        }

        # `dotnet tool run` resolves the local tool directly, without relying on
        # `dotnet ef` being discoverable on PATH.
        dotnet tool run dotnet-ef migrations add Initial --project $csproj --output-dir "Migrations/$($provider.Folder)"
        if ($LASTEXITCODE -ne 0) { throw "Migration generation failed for $($provider.Option)." }

        $target = Join-Path $content "src/StarterAspMVCEditorTemplates/Migrations/$($provider.Folder)"
        Remove-Item $target -Recurse -Force -ErrorAction SilentlyContinue
        New-Item -ItemType Directory -Force -Path (Split-Path $target -Parent) | Out-Null
        Copy-Item (Join-Path $projectDir "src/MigrationHost/Migrations/$($provider.Folder)") $target -Recurse

        # Generated files carry the throwaway project name. Put the token back so
        # sourceName substitution works for a real project.
        Get-ChildItem $target -Filter *.cs -Recurse | ForEach-Object {
            (Get-Content $_.FullName -Raw).Replace('MigrationHost', 'StarterAspMVCEditorTemplates') |
                Set-Content $_.FullName -NoNewline
        }
    }

    Remove-Item $work -Recurse -Force -ErrorAction SilentlyContinue
    Write-Host 'Migrations regenerated. Review the diff and commit.' -ForegroundColor Green
}
finally {
    Pop-Location
}
