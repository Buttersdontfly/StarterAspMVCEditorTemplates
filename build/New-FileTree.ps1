#!/usr/bin/env pwsh
<#
.SYNOPSIS
    Regenerates documentation/file-tree.md. Run after adding or moving files.
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$repo = Split-Path $PSScriptRoot -Parent
$skip = @('.git', 'bin', 'obj', 'node_modules', 'artifacts', 'out')

$preamble = @'
Generated by `build/New-FileTree.ps1`. Do not edit by hand.

Two nesting levels are easy to confuse, so read the tree with this in mind:

- `src/StarterAspMVCEditorTemplates.Templates/` is the **template package** --
  the thing that gets packed and pushed to NuGet.
- `.../content/StarterAspMVCEditorTemplates/` is the **generated project** --
  what a user gets from `dotnet new`. Its own `src/` and `tests/` become the
  user's solution layout, and `sourceName` rewrites that folder name to the
  user's project name.

Note that there are TWO test projects, answering different questions:

- `tests/` at the repo root tests the TEMPLATE: what each combo generates, and
  that both compile.
- `.../content/.../tests/` ships INSIDE generated projects and tests the running
  app: account flows, editor template gallery.

So this path in the repo:

    content/StarterAspMVCEditorTemplates/src/StarterAspMVCEditorTemplates/Program.cs

becomes this in a generated project:

    MyApp/src/MyApp/Program.cs
'@

$pending = @'
