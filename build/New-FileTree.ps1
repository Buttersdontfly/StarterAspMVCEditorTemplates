function Get-Tree([string]$Path, [string]$Prefix = '') {
    $entries = Get-ChildItem $Path -Force | Where-Object { $_.Name -notin $skip }
    $dirs = @($entries | Where-Object { $_.PSIsContainer } | Sort-Object Name)
    $files = @($entries | Where-Object { -not $_.PSIsContainer } | Sort-Object Name)
    $ordered = $dirs + $files

    $lines = @()
    for ($i = 0; $i -lt $ordered.Count; $i++) {
        $entry = $ordered[$i]
        $last = ($i -eq $ordered.Count - 1)
        $branch = if ($last) { '+-- ' } else { '|-- ' }
        $suffix = if ($entry.PSIsContainer) { '/' } else { '' }
        $lines += "$Prefix$branch$($entry.Name)$suffix"
        if ($entry.PSIsContainer) {
            $lines += Get-Tree $entry.FullName ($Prefix + $(if ($last) { '    ' } else { '|   ' }))
        }
    }
    return $lines
}

$tree = Get-Tree $repo
$out = Join-Path $repo 'documentation/file-tree.md'

$body = @(
    '# File tree'
    ''
    $preamble
    ''
    '## Current layout'
    ''
    '```'
    'StarterAspMVCEditorTemplates/'
    $tree
    '```'
    ''
    $pending
) -join "`n"

Set-Content -Path $out -Value $body
Write-Host "documentation/file-tree.md updated ($($tree.Count) entries)." -ForegroundColor Green
